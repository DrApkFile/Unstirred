#!/usr/bin/env python3
"""The README's status table, rendered from CLAIMS.md.

The ledger is the source: a claim exists in one place, with one status and one evidence file, and
the README shows that ledger rather than restating it in prose that can drift from it. Run with no
argument to rewrite the table between the markers in README.md; run with --check to fail if what
is there is not what this script would write, which is how scripts/gate.sh holds the two together.
"""

import pathlib
import sys

START = "<!-- status table: generated by scripts/status-table.py from CLAIMS.md; do not edit -->"
END = "<!-- end status table -->"
ORDER = ["PROVEN", "MEASURED", "GATED", "SYNTHETIC", "NOT BUILT"]
MEANING = {
    "PROVEN": "a recorded run against the real Zcash testnet",
    "MEASURED": "a recorded run of a named tool, against something this repo serves",
    "GATED": "settled by a recorded `scripts/gate.sh` run: fmt, clippy and the whole suite",
    "SYNTHETIC": "true of a wallet, nullifier set or root built inside the test process",
    "NOT BUILT": "named here so it cannot be read as working",
}


def rows(ledger):
    for line in ledger.read_text().splitlines():
        if not line.startswith("|") or set(line) <= set("|- "):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if cells[:2] == ["Claim", "Status"]:
            continue
        yield cells[0], cells[1], cells[2]


def table(ledger):
    found = list(rows(ledger))
    unknown = sorted({status for _, status, _ in found} - set(ORDER))
    if unknown:
        sys.exit(f"status-table: CLAIMS.md uses a status this script does not know: {unknown}")
    lines = [START, "", "| Status | Claim | Evidence |", "|---|---|---|"]
    for status in ORDER:
        for claim, _, evidence in (row for row in found if row[1] == status):
            lines.append(f"| **{status}** | {claim} | {evidence} |")
    counts = ", ".join(f"{sum(1 for row in found if row[1] == status)} {status}" for status in ORDER)
    lines += [
        "",
        f"{len(found)} claims: {counts}. "
        + "; ".join(f"**{status}** — {MEANING[status]}" for status in ORDER)
        + ".",
        "",
        END,
    ]
    return "\n".join(lines)


def main():
    readme = pathlib.Path("README.md")
    text = readme.read_text()
    if START not in text or END not in text:
        sys.exit(f"status-table: README.md has no table markers ({START} … {END})")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    rendered = head + table(pathlib.Path("CLAIMS.md")) + tail
    if "--check" in sys.argv:
        if rendered != text:
            sys.exit(
                "STATUS TABLE FAILED: README.md's status table is not what CLAIMS.md says.\n"
                "  Run: python3 -I scripts/status-table.py"
            )
        print(f"status table: README.md matches CLAIMS.md ({len(list(rows(pathlib.Path('CLAIMS.md'))))} claims)")
        return
    readme.write_text(rendered)
    print(f"status table: wrote {len(list(rows(pathlib.Path('CLAIMS.md'))))} claims into README.md")


main()
